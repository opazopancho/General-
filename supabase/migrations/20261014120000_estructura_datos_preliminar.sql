CREATE TABLE IF NOT EXISTS camiones (
    id_camion           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_camion       text        NOT NULL UNIQUE,
    modelo_camion       text        NOT NULL,
    estado_operacional  text        NOT NULL DEFAULT 'operativo'
                        CHECK (estado_operacional IN ('operativo','derivado_a_taller','en_taller','fuera_de_servicio')),
    creado_por          uuid        NOT NULL REFERENCES usuarios (id_usuario),
    creado_en           timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE  camiones IS 'Camiones de extracción (CAEX) de la flota. El horómetro no se guarda aquí: se registra en cada pasada.';
COMMENT ON COLUMN camiones.id_camion          IS 'Clave del camión.';
COMMENT ON COLUMN camiones.codigo_camion      IS 'Código interno de la faena; único.';
COMMENT ON COLUMN camiones.modelo_camion      IS 'Modelo del CAEX (Cat 793, 797, 798; Komatsu 930E, 960E).';
COMMENT ON COLUMN camiones.estado_operacional IS 'Lista: operativo, derivado_a_taller (tras alerta de daño crítico), en_taller, fuera_de_servicio.';
COMMENT ON COLUMN camiones.creado_por         IS 'Quién dio de alta el camión.';
COMMENT ON COLUMN camiones.creado_en          IS 'Fecha y hora del alta.';

CREATE TABLE IF NOT EXISTS tipos_neumatico (
    id_tipo_neumatico     bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca                 text         NOT NULL,
    medida                text         NOT NULL,
    profundidad_nueva_mm  numeric(5,1) CHECK (profundidad_nueva_mm > 0),
    umbral_retiro_mm      numeric(4,1) NOT NULL DEFAULT 20.0 CHECK (umbral_retiro_mm > 0),
    tasa_nominal_mm_100h  numeric(4,2) NOT NULL DEFAULT 1.10 CHECK (tasa_nominal_mm_100h > 0),
    creado_por            uuid         NOT NULL REFERENCES usuarios (id_usuario),
    creado_en             timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (marca, medida),
    CHECK (profundidad_nueva_mm IS NULL OR profundidad_nueva_mm > umbral_retiro_mm)
);
COMMENT ON TABLE  tipos_neumatico IS 'Marca y medida de neumático OTR, con su umbral de retiro seguro configurable.';
COMMENT ON COLUMN tipos_neumatico.id_tipo_neumatico    IS 'Clave del tipo de neumático.';
COMMENT ON COLUMN tipos_neumatico.marca                IS 'Fabricante (Michelin, Bridgestone, BKT...).';
COMMENT ON COLUMN tipos_neumatico.medida               IS 'Medida comercial del neumático.';
COMMENT ON COLUMN tipos_neumatico.profundidad_nueva_mm IS 'Profundidad de banda nueva según el fabricante; sirve para detectar lecturas imposibles.';
COMMENT ON COLUMN tipos_neumatico.umbral_retiro_mm     IS 'Profundidad mínima de retiro seguro; la proyección calcula cuándo se alcanza.';
COMMENT ON COLUMN tipos_neumatico.tasa_nominal_mm_100h IS 'Desgaste supuesto cuando aún no hay mediciones suficientes (tasa «nominal»).';
COMMENT ON COLUMN tipos_neumatico.creado_por           IS 'Quién registró el tipo.';
COMMENT ON COLUMN tipos_neumatico.creado_en            IS 'Fecha y hora del registro.';

CREATE TABLE IF NOT EXISTS neumaticos (
    id_neumatico       bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial             text        NOT NULL UNIQUE,
    id_tipo_neumatico  bigint      NOT NULL REFERENCES tipos_neumatico (id_tipo_neumatico),
    rfid               text        UNIQUE,
    estado_neumatico   text        NOT NULL DEFAULT 'disponible'
                       CHECK (estado_neumatico IN ('disponible','montado','en_reparacion','dado_de_baja')),
    fecha_ingreso      date        NOT NULL,
    creado_por         uuid        NOT NULL REFERENCES usuarios (id_usuario),
    creado_en          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_neumaticos_tipo ON neumaticos (id_tipo_neumatico);
COMMENT ON TABLE  neumaticos IS 'Cada neumático, identificado por su número de serie. Su historia se arma con montajes, mediciones y proyecciones.';
COMMENT ON COLUMN neumaticos.id_neumatico      IS 'Clave del neumático.';
COMMENT ON COLUMN neumaticos.serial            IS 'Número de serie grabado en el flanco; único.';
COMMENT ON COLUMN neumaticos.id_tipo_neumatico IS 'Marca y medida (clave externa a tipos_neumatico).';
COMMENT ON COLUMN neumaticos.rfid              IS 'Código RFID, si el neumático lo tiene.';
COMMENT ON COLUMN neumaticos.estado_neumatico  IS 'Lista: disponible (en bodega), montado, en_reparacion, dado_de_baja.';
COMMENT ON COLUMN neumaticos.fecha_ingreso     IS 'Fecha de ingreso a la faena.';
COMMENT ON COLUMN neumaticos.creado_por        IS 'Quién registró el neumático.';
COMMENT ON COLUMN neumaticos.creado_en         IS 'Fecha y hora del registro.';

