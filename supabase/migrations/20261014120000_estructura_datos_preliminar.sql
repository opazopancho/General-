           n.id_neumatico, n.serial, tn.marca,
           um.codigo_medicion, um.profundidad_mm, um.temperatura_flanco_c, um.fecha_pasada,
           up.tasa_desgaste_mm_100h, up.tipo_tasa, up.horas_remanentes,
           coalesce(up.zona, 'sin_datos') AS zona,
           up.modelo_version,
           coalesce(nd.nivel_dano, 0) AS nivel_dano
    FROM montajes mo
    JOIN camiones ca        ON ca.id_camion = mo.id_camion
    JOIN neumaticos n       ON n.id_neumatico = mo.id_neumatico
    JOIN tipos_neumatico tn ON tn.id_tipo_neumatico = n.id_tipo_neumatico
    LEFT JOIN LATERAL (
        SELECT m.id_medicion, m.codigo_medicion, m.profundidad_mm, m.temperatura_flanco_c, pa.fecha_pasada
        FROM mediciones m JOIN pasadas pa ON pa.id_pasada = m.id_pasada
        WHERE m.id_neumatico = n.id_neumatico AND m.estado_calidad = 'valida'
        ORDER BY pa.fecha_pasada DESC LIMIT 1
    ) um ON true
    LEFT JOIN LATERAL (
        SELECT pr.tasa_desgaste_mm_100h, pr.tipo_tasa, pr.horas_remanentes, pr.zona, vm.modelo_version
        FROM proyecciones pr JOIN versiones_modelo vm ON vm.id_version_modelo = pr.id_version_modelo
        WHERE pr.id_medicion = um.id_medicion
        ORDER BY pr.creado_en DESC LIMIT 1
    ) up ON true
    LEFT JOIN LATERAL (
        SELECT max(dv.nivel_dano) AS nivel_dano FROM v_danos_vigentes dv WHERE dv.id_medicion = um.id_medicion
    ) nd ON true
    WHERE mo.desmontado_en IS NULL
)
SELECT row_number() OVER (ORDER BY (nivel_dano = 3) DESC, horas_remanentes ASC NULLS LAST, codigo_camion, posicion) AS prioridad,
       *
FROM base;

-- P1 / Camiones · resumen por camión (HU-03, HU-F03): horómetro, críticos y peor daño.
CREATE OR REPLACE VIEW v_camiones_resumen WITH (security_invoker = true) AS
SELECT ca.id_camion,
       ca.codigo_camion,
       ca.modelo_camion,
       ca.estado_operacional,
       up.horometro_h,
       up.fecha_pasada AS fecha_ultima_pasada,
       count(*) FILTER (WHERE t.zona = 'rojo' OR t.nivel_dano = 3) AS cantidad_neumaticos_criticos,
       coalesce(max(t.nivel_dano), 0)                            AS nivel_dano_camion,
       count(*) FILTER (WHERE t.zona = 'sin_datos')              AS posiciones_sin_datos
FROM camiones ca
LEFT JOIN v_tablero_turno t ON t.id_camion = ca.id_camion
LEFT JOIN LATERAL (
    SELECT pa.horometro_h, pa.fecha_pasada FROM pasadas pa
    WHERE pa.id_camion = ca.id_camion ORDER BY pa.fecha_pasada DESC LIMIT 1
) up ON true
GROUP BY ca.id_camion, ca.codigo_camion, ca.modelo_camion, ca.estado_operacional, up.horometro_h, up.fecha_pasada;

-- P2 · Ficha del neumático (HU-04, HU-F04): historial de pasadas para la curva de desgaste.
CREATE OR REPLACE VIEW v_historial_neumatico WITH (security_invoker = true) AS
SELECT n.serial,
       m.codigo_medicion,
       pa.fecha_pasada,
       ca.codigo_camion,
       m.posicion,
       m.horas_operacion_neumatico,
       m.profundidad_mm,
       tn.umbral_retiro_mm,
       m.temperatura_flanco_c,
       m.estado_calidad,
       m.motivo_descarte,
       m.foto_url,
       pr.tasa_desgaste_mm_100h,
       pr.tipo_tasa,
       pr.horas_remanentes,
       pr.zona,
       vm.modelo_version
FROM mediciones m
JOIN neumaticos n       ON n.id_neumatico = m.id_neumatico
JOIN tipos_neumatico tn ON tn.id_tipo_neumatico = n.id_tipo_neumatico
JOIN pasadas pa         ON pa.id_pasada = m.id_pasada
JOIN camiones ca        ON ca.id_camion = pa.id_camion
LEFT JOIN proyecciones pr     ON pr.id_medicion = m.id_medicion
LEFT JOIN versiones_modelo vm ON vm.id_version_modelo = pr.id_version_modelo;

-- P3 · Agendar intervención (HU-06, HU-F09): cupos libres calculados, no guardados.
CREATE OR REPLACE VIEW v_ventanas_disponibles WITH (security_invoker = true) AS
SELECT v.id_ventana,
       (v.inicio AT TIME ZONE 'America/Santiago')::date AS dia,
       v.turno,
       v.inicio,
       v.fin,
       v.cupos_totales,
       count(o.id_orden)                    AS cupos_ocupados,
       v.cupos_totales - count(o.id_orden)  AS cupos_libres
FROM ventanas_taller v
LEFT JOIN ordenes_trabajo o ON o.id_ventana = v.id_ventana AND o.estado_orden = 'programada'
GROUP BY v.id_ventana;

-- P4 / Órdenes de trabajo (HU-07, HU-F07, HU-F08): cada orden con su trazabilidad completa.
CREATE OR REPLACE VIEW v_ordenes_trabajo WITH (security_invoker = true) AS
SELECT o.id_orden,
       o.codigo_orden,
       o.estado_orden,
       o.tipo_intervencion,
       n.serial,
       ca.codigo_camion,
       m.posicion,
       (v.inicio AT TIME ZONE 'America/Santiago')::date AS dia,
       v.turno,
       o.nota,
       pr.horas_remanentes AS horas_remanentes_al_emitir,
       pr.zona             AS zona_al_emitir,
       pr.tasa_desgaste_mm_100h,
       pr.tipo_tasa,
       m.codigo_medicion,
       m.profundidad_mm,
       pa.fecha_pasada,
       vm.modelo_version,
       nr.serial  AS serial_reemplazo,
       u.nombre   AS emitida_por,
       o.creado_en AS emitida_en,
       o.estado_erp,
       o.codigo_erp
FROM ordenes_trabajo o
JOIN neumaticos n        ON n.id_neumatico = o.id_neumatico
JOIN proyecciones pr     ON pr.id_proyeccion = o.id_proyeccion
JOIN versiones_modelo vm ON vm.id_version_modelo = pr.id_version_modelo
JOIN mediciones m        ON m.id_medicion = pr.id_medicion
JOIN pasadas pa          ON pa.id_pasada = m.id_pasada
JOIN camiones ca         ON ca.id_camion = pa.id_camion
JOIN ventanas_taller v   ON v.id_ventana = o.id_ventana
LEFT JOIN usuarios u     ON u.id_usuario = o.creado_por   -- LEFT: sin sesión no se ven los usuarios
LEFT JOIN neumaticos nr  ON nr.id_neumatico = o.id_neumatico_reemplazo;

-- Indicadores de la hipótesis (roadmap «Después»): cada desmontaje con su anticipación medida.
CREATE OR REPLACE VIEW v_indicadores_retiro WITH (security_invoker = true) AS
SELECT n.serial,
       ca.codigo_camion,
       mo.posicion,
       mo.desmontado_en,
       mo.motivo_desmontaje,
       mo.horas_neumatico_al_desmontar AS horas_vida_util,
       pr_rojo.horas_operacion_neumatico AS horas_en_primera_zona_roja,
       mo.horas_neumatico_al_desmontar - pr_rojo.horas_operacion_neumatico AS anticipacion_h
FROM montajes mo
JOIN neumaticos n ON n.id_neumatico = mo.id_neumatico
JOIN camiones ca  ON ca.id_camion   = mo.id_camion
LEFT JOIN LATERAL (
    SELECT m.horas_operacion_neumatico
    FROM proyecciones pr
    JOIN mediciones m ON m.id_medicion = pr.id_medicion
    JOIN pasadas pa   ON pa.id_pasada  = m.id_pasada
    WHERE pr.id_neumatico = mo.id_neumatico AND pr.zona = 'rojo'
      AND pa.fecha_pasada BETWEEN mo.montado_en AND mo.desmontado_en
    ORDER BY pa.fecha_pasada ASC LIMIT 1
) pr_rojo ON true
WHERE mo.desmontado_en IS NOT NULL;

COMMENT ON VIEW v_danos_vigentes       IS 'Daños con la última corrección aplicada y la marca «por confirmar».';
COMMENT ON VIEW v_tablero_turno        IS 'P1 Tablero del turno: una fila por posición ocupada, ordenada por prioridad (daño 3 primero, luego menos horas).';
COMMENT ON VIEW v_camiones_resumen     IS 'Camiones: horómetro, última pasada, neumáticos críticos y peor nivel de daño.';
COMMENT ON VIEW v_historial_neumatico  IS 'P2 Ficha: historial de pasadas de cada serial para la curva de desgaste.';
COMMENT ON VIEW v_ventanas_disponibles IS 'P3 Agendar: ventanas con cupos libres calculados.';
COMMENT ON VIEW v_ordenes_trabajo      IS 'P4 y Órdenes: cada orden con su medición, pasada y versión del modelo.';
COMMENT ON VIEW v_indicadores_retiro   IS 'Indicadores de éxito: motivo de cada retiro, horas de vida útil y anticipación medida.';

-- =============================================================================
-- SEGURIDAD EN SUPABASE (Row Level Security)
-- Solo se aplica si existen los roles de Supabase (anon, authenticated).
-- Prototipo con datos sintéticos: se puede leer sin iniciar sesión; para escribir
-- hay que iniciar sesión. Ninguna política permite borrar.
-- Cuando entren datos reales, quitar la lectura de «anon».
-- =============================================================================
DO $$
DECLARE
    t text;
    tablas text[] := ARRAY['versiones_modelo','camiones','tipos_neumatico','neumaticos','porticos','sensores',
                           'pasadas','mediciones','danos','correcciones_dano','proyecciones','alertas',
                           'ventanas_taller','ordenes_trabajo','historial_ordenes','montajes'];
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
       OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        RAISE NOTICE 'Roles de Supabase no encontrados: se omite RLS (base local de prueba).';
        RETURN;
    END IF;

    FOREACH t IN ARRAY tablas || ARRAY['usuarios'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON %I', 'leer_' || t, t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON %I', 'agregar_' || t, t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON %I', 'actualizar_' || t, t);
        EXECUTE format('CREATE POLICY %I ON %I FOR INSERT TO authenticated WITH CHECK (true)', 'agregar_' || t, t);
        EXECUTE format('CREATE POLICY %I ON %I FOR UPDATE TO authenticated USING (true) WITH CHECK (true)', 'actualizar_' || t, t);
    END LOOP;

    FOREACH t IN ARRAY tablas LOOP
        EXECUTE format('CREATE POLICY %I ON %I FOR SELECT TO anon, authenticated USING (true)', 'leer_' || t, t);
    END LOOP;
    -- Los correos de usuarios no se exponen sin sesión.
    EXECUTE 'CREATE POLICY leer_usuarios ON usuarios FOR SELECT TO authenticated USING (true)';
END $$;
