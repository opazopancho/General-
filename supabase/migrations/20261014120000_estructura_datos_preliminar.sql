-- Daño vigente: el detectado, o el de su última corrección.
CREATE OR REPLACE VIEW v_danos_vigentes WITH (security_invoker = true) AS
SELECT d.id_dano,
       d.id_medicion,
       m.id_neumatico,
       coalesce(c.tipo_dano_nuevo,  d.tipo_dano)  AS tipo_dano,
       coalesce(c.nivel_dano_nuevo, d.nivel_dano) AS nivel_dano,
       d.confianza,
       (c.id_correccion IS NULL AND d.origen_deteccion = 'modelo'
        AND d.confianza < coalesce(vm.confianza_minima, 0.70)) AS por_confirmar,
       c.id_correccion IS NOT NULL AS corregido,
       d.zona_neumatico,
       d.caja_delimitadora,
       m.foto_url,
       p.fecha_pasada,
       vm.modelo_version
FROM danos d
JOIN mediciones m ON m.id_medicion = d.id_medicion
JOIN pasadas p    ON p.id_pasada   = m.id_pasada
LEFT JOIN versiones_modelo vm ON vm.id_version_modelo = d.id_version_modelo
LEFT JOIN LATERAL (
    SELECT cd.* FROM correcciones_dano cd
    WHERE cd.id_dano = d.id_dano
    ORDER BY cd.creado_en DESC, cd.id_correccion DESC
    LIMIT 1
) c ON true;

