CREATE TABLE IF NOT EXISTS porticos (
    id_portico      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_portico  text        NOT NULL UNIQUE,
    ubicacion       text        NOT NULL,
    estado_portico  text        NOT NULL DEFAULT 'operativo'
                    CHECK (estado_portico IN ('operativo','en_revision','fuera_de_servicio','simulado')),
    calibrado_en    timestamptz,
    creado_por      uuid        NOT NULL REFERENCES usuarios (id_usuario),
    creado_en       timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE  porticos IS 'Pórtico instrumentado en un punto obligatorio de tránsito. En el semestre es simulado (datos sintéticos).';
COMMENT ON COLUMN porticos.id_portico     IS 'Clave del pórtico.';
COMMENT ON COLUMN porticos.codigo_portico IS 'Código del pórtico; único.';
COMMENT ON COLUMN porticos.ubicacion      IS 'Punto de tránsito donde está instalado.';
COMMENT ON COLUMN porticos.estado_portico IS 'Lista: operativo, en_revision (tras alerta 4a), fuera_de_servicio, simulado.';
COMMENT ON COLUMN porticos.calibrado_en   IS 'Fecha y hora de la última calibración (precondición del caso de uso).';
COMMENT ON COLUMN porticos.creado_por     IS 'Quién registró el pórtico.';
COMMENT ON COLUMN porticos.creado_en      IS 'Fecha y hora del registro.';

CREATE TABLE IF NOT EXISTS sensores (
    id_sensor         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_portico        bigint      NOT NULL REFERENCES porticos (id_portico),
    codigo_sensor     text        NOT NULL UNIQUE,
    tipo_sensor       text        NOT NULL CHECK (tipo_sensor IN ('camara','escaner_3d','termografia','rfid','detector_paso')),
    ubicacion_sensor  text        NOT NULL,
    cobertura         text,
    estado_sensor     text        NOT NULL DEFAULT 'operativo' CHECK (estado_sensor IN ('operativo','con_falla','fuera_de_servicio')),
    creado_por        uuid        NOT NULL REFERENCES usuarios (id_usuario),
    creado_en         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_sensores_portico ON sensores (id_portico);
COMMENT ON TABLE  sensores IS 'Cámaras, escáner 3D, termografía y lector RFID montados en cada pórtico.';
COMMENT ON COLUMN sensores.id_sensor        IS 'Clave del sensor.';
COMMENT ON COLUMN sensores.id_portico       IS 'Pórtico donde está montado (clave externa).';
COMMENT ON COLUMN sensores.codigo_sensor    IS 'Código del sensor; único.';
COMMENT ON COLUMN sensores.tipo_sensor      IS 'Lista: camara, escaner_3d, termografia, rfid, detector_paso.';
COMMENT ON COLUMN sensores.ubicacion_sensor IS 'Dónde está en el pórtico.';
COMMENT ON COLUMN sensores.cobertura        IS 'Qué posiciones o zonas del neumático cubre.';
COMMENT ON COLUMN sensores.estado_sensor    IS 'Lista: operativo, con_falla, fuera_de_servicio.';
COMMENT ON COLUMN sensores.creado_por       IS 'Quién registró el sensor.';
COMMENT ON COLUMN sensores.creado_en        IS 'Fecha y hora del registro.';

CREATE TABLE IF NOT EXISTS pasadas (
    id_pasada      bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_portico     bigint       NOT NULL REFERENCES porticos (id_portico),
    id_camion      bigint       NOT NULL REFERENCES camiones (id_camion),
    fecha_pasada   timestamptz  NOT NULL,
    velocidad_kmh  numeric(3,1) NOT NULL CHECK (velocidad_kmh > 0),
    horometro_h    integer      NOT NULL CHECK (horometro_h >= 0),
    origen_dato    text         NOT NULL DEFAULT 'sintetico' CHECK (origen_dato IN ('sintetico','portico','manual')),
    creado_por     uuid         NOT NULL REFERENCES usuarios (id_usuario),
    creado_en      timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (id_camion, fecha_pasada)
);
CREATE INDEX IF NOT EXISTS ix_pasadas_portico ON pasadas (id_portico);
COMMENT ON TABLE  pasadas IS 'Cada vez que un CAEX cruza el pórtico (paso 1 del caso de uso). Una pasada genera hasta seis mediciones.';
COMMENT ON COLUMN pasadas.id_pasada     IS 'Clave de la pasada.';
COMMENT ON COLUMN pasadas.id_portico    IS 'Pórtico que registró la pasada (clave externa).';
COMMENT ON COLUMN pasadas.id_camion     IS 'Camión que cruzó (clave externa).';
COMMENT ON COLUMN pasadas.fecha_pasada  IS 'Fecha y hora del cruce.';
COMMENT ON COLUMN pasadas.velocidad_kmh IS 'Velocidad de cruce; el caso de uso opera entre 2 y 5 km/h.';
COMMENT ON COLUMN pasadas.horometro_h   IS 'Horómetro del camión al cruzar.';
COMMENT ON COLUMN pasadas.origen_dato   IS 'Lista: sintetico (semestre), portico (instalación real), manual.';
COMMENT ON COLUMN pasadas.creado_por    IS 'Proceso o persona que cargó la pasada.';
COMMENT ON COLUMN pasadas.creado_en     IS 'Fecha y hora de carga.';

CREATE SEQUENCE IF NOT EXISTS mediciones_codigo_seq;

CREATE TABLE IF NOT EXISTS mediciones (
    id_medicion                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_medicion            text         NOT NULL UNIQUE
                               DEFAULT ('med-' || lpad(nextval('mediciones_codigo_seq')::text, 5, '0')),
    id_pasada                  bigint       NOT NULL REFERENCES pasadas (id_pasada),
    posicion                   smallint     NOT NULL CHECK (posicion BETWEEN 1 AND 6),
    id_neumatico               bigint       REFERENCES neumaticos (id_neumatico),
    estado_identificacion      text         NOT NULL DEFAULT 'identificado'
                               CHECK (estado_identificacion IN ('identificado','pendiente','verificacion_manual')),
    metodo_identificacion      text         CHECK (metodo_identificacion IN ('ocr_serial','rfid','manual')),
    profundidad_mm             numeric(5,1) CHECK (profundidad_mm >= 0),
    temperatura_flanco_c       numeric(4,1),
    horas_operacion_neumatico  integer      CHECK (horas_operacion_neumatico >= 0),
    estado_calidad             text         NOT NULL DEFAULT 'valida'
                               CHECK (estado_calidad IN ('valida','fuera_tolerancia','rechazada')),
    motivo_descarte            text,
    foto_url                   text,
    nube_puntos_url            text,
    termografia_url            text,
    creado_por                 uuid         NOT NULL REFERENCES usuarios (id_usuario),
    creado_en                  timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (id_pasada, posicion),
    UNIQUE (id_medicion, id_neumatico),
    CHECK ((estado_identificacion = 'identificado') = (id_neumatico IS NOT NULL)),
    CHECK ((estado_identificacion = 'identificado') = (metodo_identificacion IS NOT NULL)),
    CHECK (estado_calidad <> 'valida' OR profundidad_mm IS NOT NULL),
    CHECK (id_neumatico IS NULL OR estado_calidad <> 'valida' OR horas_operacion_neumatico IS NOT NULL),
    CHECK (estado_calidad = 'valida' OR coalesce(trim(motivo_descarte), '') <> '')
);
CREATE INDEX IF NOT EXISTS ix_mediciones_neumatico ON mediciones (id_neumatico);
COMMENT ON TABLE  mediciones IS 'Condición de un neumático en una pasada: profundidad, temperatura, horas y evidencia (pasos 2 a 4). Cubre las extensiones 3a (serial no identificado) y 4a (fuera de tolerancia).';
COMMENT ON COLUMN mediciones.id_medicion               IS 'Clave de la medición.';
COMMENT ON COLUMN mediciones.codigo_medicion           IS 'Código legible que aparece en la orden como origen; se genera solo.';
COMMENT ON COLUMN mediciones.id_pasada                 IS 'Pasada en que se capturó (clave externa).';
COMMENT ON COLUMN mediciones.posicion                  IS 'Posición en el camión: 1-2 eje delantero; 3-6 tándem trasero dual.';
COMMENT ON COLUMN mediciones.id_neumatico              IS 'Neumático medido (clave externa). Vacío mientras el serial no se identifica (extensión 3a).';
COMMENT ON COLUMN mediciones.estado_identificacion     IS 'Lista: identificado, pendiente, verificacion_manual (tras tres pasadas sin identificar).';
COMMENT ON COLUMN mediciones.metodo_identificacion     IS 'Lista: ocr_serial, rfid, manual. Obligatorio cuando está identificado.';
COMMENT ON COLUMN mediciones.profundidad_mm            IS 'Profundidad remanente de la banda medida por el escáner 3D.';
COMMENT ON COLUMN mediciones.temperatura_flanco_c      IS 'Temperatura superficial del flanco medida por termografía.';
COMMENT ON COLUMN mediciones.horas_operacion_neumatico IS 'Horas acumuladas del neumático al momento de la medición. Obligatoria si la medición es válida y el neumático está identificado.';
COMMENT ON COLUMN mediciones.estado_calidad            IS 'Lista: valida, fuera_tolerancia (suciedad o ruido, extensión 4a), rechazada (valor imposible).';
COMMENT ON COLUMN mediciones.motivo_descarte           IS 'Por qué no es válida. Obligatorio si no es válida.';
COMMENT ON COLUMN mediciones.foto_url                  IS 'Ruta de la foto en Supabase Storage.';
COMMENT ON COLUMN mediciones.nube_puntos_url           IS 'Ruta del archivo del escáner 3D en Supabase Storage.';
COMMENT ON COLUMN mediciones.termografia_url           IS 'Ruta de la imagen térmica en Supabase Storage.';
COMMENT ON COLUMN mediciones.creado_por                IS 'Proceso del pórtico o persona que registró la medición (HU-F04).';
COMMENT ON COLUMN mediciones.creado_en                 IS 'Fecha y hora del registro.';

