CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario  uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre      text        NOT NULL,
    correo      text        NOT NULL UNIQUE CHECK (correo LIKE '%_@_%'),
    rol         text        NOT NULL CHECK (rol IN ('planificador','despachador','operador_portico','taller','administrador','sistema')),
    activo      boolean     NOT NULL DEFAULT true,
    creado_por  uuid        REFERENCES usuarios (id_usuario),
    creado_en   timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE  usuarios IS 'Personas y procesos automáticos que crean o modifican registros. Cuando exista login, id_usuario será el mismo id de auth.users de Supabase.';
COMMENT ON COLUMN usuarios.id_usuario IS 'Clave del usuario (uuid, igual al id de auth.users cuando se active el login).';
COMMENT ON COLUMN usuarios.nombre     IS 'Nombre visible en la interfaz y en la bitácora.';
COMMENT ON COLUMN usuarios.correo     IS 'Correo de acceso; único.';
COMMENT ON COLUMN usuarios.rol        IS 'Lista: planificador, despachador, operador_portico, taller, administrador, sistema (pórtico y modelo).';
COMMENT ON COLUMN usuarios.activo     IS 'Falso cuando la persona deja el equipo; no se borra para conservar la autoría.';
COMMENT ON COLUMN usuarios.creado_por IS 'Quién creó el usuario. Vacío solo para el primer usuario (arranque).';
COMMENT ON COLUMN usuarios.creado_en  IS 'Fecha y hora de creación del registro.';

CREATE TABLE IF NOT EXISTS versiones_modelo (
    id_version_modelo   bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo_version      text         NOT NULL UNIQUE,
    descripcion         text         NOT NULL,
    umbral_rojo_h       integer      NOT NULL DEFAULT 200 CHECK (umbral_rojo_h > 0),
    umbral_amarillo_h   integer      NOT NULL DEFAULT 500,
    confianza_minima    numeric(3,2) NOT NULL DEFAULT 0.70 CHECK (confianza_minima BETWEEN 0 AND 1),
    mediciones_minimas  smallint     NOT NULL DEFAULT 2 CHECK (mediciones_minimas >= 1),
    vigente             boolean      NOT NULL DEFAULT false,
    creado_por          uuid         NOT NULL REFERENCES usuarios (id_usuario),
    creado_en           timestamptz  NOT NULL DEFAULT now(),
    CHECK (umbral_amarillo_h > umbral_rojo_h)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_versiones_modelo_una_vigente ON versiones_modelo (vigente) WHERE vigente;
COMMENT ON TABLE  versiones_modelo IS 'Cada versión del modelo de proyección y los umbrales que usó. Permite saber con qué reglas se emitió cada orden.';
COMMENT ON COLUMN versiones_modelo.id_version_modelo  IS 'Clave de la versión.';
COMMENT ON COLUMN versiones_modelo.modelo_version     IS 'Nombre corto de la versión, el que se muestra en la orden.';
COMMENT ON COLUMN versiones_modelo.descripcion        IS 'Qué hace esta versión del modelo.';
COMMENT ON COLUMN versiones_modelo.umbral_rojo_h      IS 'Bajo estas horas remanentes el neumático queda en zona roja.';
COMMENT ON COLUMN versiones_modelo.umbral_amarillo_h  IS 'Bajo estas horas (y sobre el rojo) queda en zona amarilla; sobre ellas, verde.';
COMMENT ON COLUMN versiones_modelo.confianza_minima   IS 'Bajo esta confianza un daño detectado se muestra como «por confirmar».';
COMMENT ON COLUMN versiones_modelo.mediciones_minimas IS 'Mediciones válidas necesarias para usar la tasa observada en vez de la nominal.';
COMMENT ON COLUMN versiones_modelo.vigente            IS 'Verdadero en la única versión que se usa hoy.';
COMMENT ON COLUMN versiones_modelo.creado_por         IS 'Quién publicó la versión.';
COMMENT ON COLUMN versiones_modelo.creado_en          IS 'Fecha y hora de publicación.';

