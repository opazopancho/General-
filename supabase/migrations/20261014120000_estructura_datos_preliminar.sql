-- Una ventana no acepta más órdenes programadas que sus cupos (HU-06, HU-F09).
CREATE OR REPLACE FUNCTION fn_validar_cupo_ventana()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
    v_cupos   smallint;
    v_usados  integer;
BEGIN
    IF NEW.estado_orden <> 'programada' THEN
        RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.estado_orden = 'programada' AND OLD.id_ventana = NEW.id_ventana THEN
        RETURN NEW;
    END IF;
    -- Bloquea la ventana para que dos planificadores no tomen el último cupo a la vez.
    SELECT cupos_totales INTO v_cupos FROM ventanas_taller WHERE id_ventana = NEW.id_ventana FOR UPDATE;
    SELECT count(*) INTO v_usados FROM ordenes_trabajo
     WHERE id_ventana = NEW.id_ventana AND estado_orden = 'programada' AND id_orden <> NEW.id_orden;
    IF v_usados >= v_cupos THEN
        RAISE EXCEPTION 'La ventana % no tiene cupos libres (% de %)', NEW.id_ventana, v_usados, v_cupos
              USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_ordenes_validar_cupo ON ordenes_trabajo;
CREATE TRIGGER trg_ordenes_validar_cupo
BEFORE INSERT OR UPDATE OF id_ventana, estado_orden ON ordenes_trabajo
FOR EACH ROW EXECUTE FUNCTION fn_validar_cupo_ventana();

-- La orden conserva su código y su origen; una orden ejecutada o anulada no cambia (HU-F09, HU-F10).
CREATE OR REPLACE FUNCTION fn_proteger_orden()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    IF NEW.codigo_orden <> OLD.codigo_orden OR NEW.id_proyeccion <> OLD.id_proyeccion
       OR NEW.id_neumatico <> OLD.id_neumatico OR NEW.creado_por <> OLD.creado_por OR NEW.creado_en <> OLD.creado_en THEN
        RAISE EXCEPTION 'La orden % conserva su código, su neumático, su origen y su autor', OLD.codigo_orden;
    END IF;
    IF OLD.estado_orden <> 'programada'
       AND (NEW.estado_orden, NEW.id_ventana, NEW.tipo_intervencion, NEW.nota, NEW.id_neumatico_reemplazo)
           IS DISTINCT FROM
           (OLD.estado_orden, OLD.id_ventana, OLD.tipo_intervencion, OLD.nota, OLD.id_neumatico_reemplazo) THEN
        RAISE EXCEPTION 'La orden % está % y no se puede modificar', OLD.codigo_orden, OLD.estado_orden;
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_ordenes_proteger ON ordenes_trabajo;
CREATE TRIGGER trg_ordenes_proteger
BEFORE UPDATE ON ordenes_trabajo
FOR EACH ROW EXECUTE FUNCTION fn_proteger_orden();

-- Toda orden nueva deja su evento de emisión en la bitácora.
CREATE OR REPLACE FUNCTION fn_registrar_emision()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    INSERT INTO historial_ordenes (id_orden, accion, id_ventana_nueva, creado_por, creado_en)
    VALUES (NEW.id_orden, 'emision', NEW.id_ventana, NEW.creado_por, NEW.creado_en);
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_ordenes_registrar_emision ON ordenes_trabajo;
CREATE TRIGGER trg_ordenes_registrar_emision
AFTER INSERT ON ordenes_trabajo
FOR EACH ROW EXECUTE FUNCTION fn_registrar_emision();

-- Lo que es evidencia no se borra; las bitácoras tampoco se editan.
CREATE OR REPLACE FUNCTION fn_bloquear_cambio()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    RAISE EXCEPTION 'Los registros de % no se borran ni se editan: son evidencia (%)', TG_TABLE_NAME, TG_OP;
END $$;

