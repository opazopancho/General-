CREATE TABLE IF NOT EXISTS danos (
    id_dano            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medicion        bigint       NOT NULL REFERENCES mediciones (id_medicion),
    id_sensor          bigint       REFERENCES sensores (id_sensor),
    tipo_dano          text         NOT NULL CHECK (tipo_dano IN ('corte_flanco','corte_banda','roca_incrustada','desgaste_irregular','sobrecalentamiento','delaminacion','otro')),
    nivel_dano         smallint     NOT NULL CHECK (nivel_dano BETWEEN 0 AND 3),
    confianza          numeric(3,2) NOT NULL CHECK (confianza BETWEEN 0 AND 1),
    zona_neumatico     text         CHECK (zona_neumatico IN ('banda','hombro','flanco_externo','flanco_interno')),
    caja_delimitadora  jsonb,
    origen_deteccion   text         NOT NULL DEFAULT 'modelo' CHECK (origen_deteccion IN ('modelo','inspeccion_manual')),
    id_version_modelo  bigint       REFERENCES versiones_modelo (id_version_modelo),
    creado_por         uuid         NOT NULL REFERENCES usuarios (id_usuario),
    creado_en          timestamptz  NOT NULL DEFAULT now(),
    CHECK (origen_deteccion <> 'modelo' OR id_version_modelo IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_danos_medicion ON danos (id_medicion);
COMMENT ON TABLE  danos IS 'Cada daño detectado en una medición (cortes, rocas, desgaste irregular, calor). Nivel 3 dispara la extensión 5a.';
COMMENT ON COLUMN danos.id_dano           IS 'Clave del daño.';
COMMENT ON COLUMN danos.id_medicion       IS 'Medición donde se detectó (clave externa).';
COMMENT ON COLUMN danos.id_sensor         IS 'Cámara o sensor que lo captó (clave externa, opcional).';
COMMENT ON COLUMN danos.tipo_dano         IS 'Lista: corte_flanco, corte_banda, roca_incrustada, desgaste_irregular, sobrecalentamiento, delaminacion, otro.';
COMMENT ON COLUMN danos.nivel_dano        IS 'Nivel 0 sin daño, 1 leve, 2 moderado, 3 crítico (sacar el CAEX del ciclo).';
COMMENT ON COLUMN danos.confianza         IS 'Certeza del modelo entre 0 y 1; 1 si lo registró una persona.';
COMMENT ON COLUMN danos.zona_neumatico    IS 'Lista: banda, hombro, flanco_externo, flanco_interno.';
COMMENT ON COLUMN danos.caja_delimitadora IS 'Recuadro del daño sobre la foto, en proporciones de la imagen: {"x","y","ancho","alto"}.';
COMMENT ON COLUMN danos.origen_deteccion  IS 'Lista: modelo (visión artificial) o inspeccion_manual.';
COMMENT ON COLUMN danos.id_version_modelo IS 'Versión del modelo que lo detectó; obligatoria si el origen es el modelo.';
COMMENT ON COLUMN danos.creado_por        IS 'Proceso o persona que registró el daño.';
COMMENT ON COLUMN danos.creado_en         IS 'Fecha y hora del registro.';

CREATE TABLE IF NOT EXISTS correcciones_dano (
    id_correccion          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dano                bigint      NOT NULL REFERENCES danos (id_dano),
    tipo_dano_anterior     text        NOT NULL,
    tipo_dano_nuevo        text        NOT NULL CHECK (tipo_dano_nuevo IN ('corte_flanco','corte_banda','roca_incrustada','desgaste_irregular','sobrecalentamiento','delaminacion','otro')),
    nivel_dano_anterior    smallint    NOT NULL CHECK (nivel_dano_anterior BETWEEN 0 AND 3),
    nivel_dano_nuevo       smallint    NOT NULL CHECK (nivel_dano_nuevo BETWEEN 0 AND 3),
    motivo                 text        NOT NULL CHECK (trim(motivo) <> ''),
    usar_para_reentrenar   boolean     NOT NULL DEFAULT true,
    creado_por             uuid        NOT NULL REFERENCES usuarios (id_usuario),
    creado_en              timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_correcciones_dano ON correcciones_dano (id_dano);
COMMENT ON TABLE  correcciones_dano IS 'Corrección humana de un daño (humano en el bucle, HU-F05). El daño original no se modifica: queda la corrección con autor, fecha y motivo.';
COMMENT ON COLUMN correcciones_dano.id_correccion        IS 'Clave de la corrección.';
